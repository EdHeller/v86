#!/usr/bin/env node
// Bundles src/parallel/{control,relocate,vcpu_worker}.js into one module worker file (build/vcpu-worker.js) that can be served
// next to libv86.js. Usage: tools/build_vcpu_worker.mjs output.js
import fs from "node:fs";

const read = name => fs.readFileSync(new URL("../src/parallel/" + name, import.meta.url), "utf8");
// (a line can declare several constants: `export const A = 1, B = 2;`)
const names = [...read("control.js").matchAll(/^export const (.*);/gm)].flatMap(m => [...m[1].matchAll(/(?:^|, )(\w+) =/g)].map(x => x[1]));
const control = read("control.js").replace(/^export /gm, "");
const relocate = read("relocate.js").replace(/^import .*$/gm, "").replace(/^export /gm, "");
const worker = read("vcpu_worker.js").replace(/^import .*$/gm, "");

const out = `// generated by tools/build_vcpu_worker.mjs: a vCPU worker of a parallel machine (docs/parallel.md)
const dbg_assert = () => {};
const C = (() => {
${control}
return { ${names.join(", ")} };
})();
${relocate}
${worker}
`;
fs.writeFileSync(process.argv[2], out);
console.log(process.argv[2] + ": " + out.length + " bytes");

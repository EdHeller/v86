#!/usr/bin/env python3
"""Generates issues/sse_alignment_matrix.asm: every legacy SSE instruction with a 128-bit memory operand,
run with an aligned address (never faults) and with a misaligned one (#GP unless the instruction allows it),
the misaligned access made inside a loop that is hot enough to be compiled by the jit.

    python3 gen_sse_alignment.py > issues/sse_alignment_matrix.asm
"""

# instructions whose 128-bit memory operand must be 16-byte aligned (loads): (mnemonic, extra operands)
LOADS = []
def add(names, imm=None):
    for n in names.split():
        LOADS.append((n, imm))

add("addps subps mulps divps sqrtps rsqrtps rcpps minps maxps andps andnps orps xorps unpcklps unpckhps movaps")
add("shufps cmpps", "1")
add("addpd subpd mulpd divpd sqrtpd minpd maxpd andpd andnpd orpd xorpd unpcklpd unpckhpd movapd")
add("shufpd cmppd", "1")
add("cvtdq2ps cvtps2dq cvttps2dq cvtpd2ps cvtpd2dq cvttpd2dq movdqa")
add("paddb paddw paddd paddq psubb psubw psubd psubq paddsb paddsw paddusb paddusw psubsb psubsw psubusb psubusw")
add("pmullw pmulhw pmulhuw pmuludq pmaddwd pcmpeqb pcmpeqw pcmpeqd pcmpgtb pcmpgtw pcmpgtd pand pandn por pxor")
add("pminub pmaxub pminsw pmaxsw pavgb pavgw psadbw packsswb packssdw packuswb")
add("punpcklbw punpcklwd punpckldq punpcklqdq punpckhbw punpckhwd punpckhdq punpckhqdq")
add("psllw pslld psllq psrlw psrld psrlq psraw psrad")
add("pshufd pshufhw pshuflw", "27")
add("addsubpd addsubps haddpd haddps hsubpd hsubps movshdup movsldup")
add("pshufb phaddw phaddd phaddsw phsubw phsubd phsubsw pmaddubsw pmulhrsw psignb psignw psignd pabsb pabsw pabsd")
add("palignr", "5")
add("pmulld pmuldq pminsb pmaxsb pminuw pmaxuw pminud pmaxud pminsd pmaxsd pcmpeqq pcmpgtq packusdw phminposuw ptest movntdqa")
add("blendps blendpd pblendw dpps dppd roundps roundpd mpsadbw", "1")   # pcmpistri/pcmpistrm/pcmpestri/pcmpestrm are not implemented (#UD)

# memory operand forms that are not 16 bytes wide or that explicitly allow any alignment
UNALIGNED_OK = [
    ("movups", "load"), ("movupd", "load"), ("movdqu", "load"), ("lddqu", "load"),
    ("movups", "store"), ("movupd", "store"), ("movdqu", "store"),
    ("movlps", "load"), ("movhps", "load"), ("movlpd", "load"), ("movhpd", "load"),
    ("movlps", "store"), ("movhps", "store"), ("movlpd", "store"), ("movhpd", "store"),
    ("movddup", "load"), ("cvtps2pd", "load"), ("cvtdq2pd", "load"),
    ("pmovsxbw", "load"), ("pmovzxbw", "load"), ("pmovsxwd", "load"), ("pmovzxwd", "load"), ("pmovsxdq", "load"), ("pmovzxdq", "load"),
]
# memory operands of 8 to 64 bits: never an alignment fault, whatever the address
SMALL_OK = ["insertps xmm1, [esi], 16", "pinsrb xmm1, [esi], 1", "pinsrw xmm1, [esi], 1", "pinsrd xmm1, [esi], 1",
            "pextrb [esi], xmm1, 1", "pextrw [esi], xmm1, 1", "pextrd [esi], xmm1, 1", "extractps [esi], xmm1, 1",
            "roundss xmm1, [esi], 1", "roundsd xmm1, [esi], 1", "movss xmm1, [esi]", "movsd xmm1, [esi]", "movd xmm1, [esi]",
            "movq xmm1, [esi]", "addss xmm1, [esi]", "addsd xmm1, [esi]", "mulss xmm1, [esi]", "sqrtsd xmm1, [esi]",
            "comiss xmm1, [esi]", "ucomisd xmm1, [esi]", "cvtss2sd xmm1, [esi]", "cvtsd2ss xmm1, [esi]", "cvtsi2sd xmm1, dword [esi]",
            "pmovsxbd xmm1, [esi]", "pmovzxbq xmm1, [esi]", "pmovsxwq xmm1, [esi]", "movntdq [esi - 4 + 4], xmm1"][:-1]
STORES_ALIGNED = ["movaps", "movapd", "movdqa", "movntps", "movntpd", "movntdq"]

import sys
LONG = "--long" in sys.argv
SKIP = set()
if "--skip" in sys.argv:
    SKIP = set(int(x) for x in sys.argv[sys.argv.index("--skip") + 1].split(",") if x)
out = []
w = out.append
w("; EXPECT: pass")
if LONG:
    w("; V86: {\"jit64_threshold\": 10, \"sync_jit\": true}")
w("; DESC: SSE alignment matrix (generated by gen_sse_alignment.py): every 128-bit memory form faults (#GP) on a misaligned address unless the instruction allows it, in interpreted and compiled code")
w('%include "inc/long.inc"' if LONG else '%include "inc/pm32.inc"')
w("""
%macro SSE_ON 0
    mov eax, cr0
    and eax, ~(1 << 2)
    or eax, 1 << 1
    mov cr0, eax
    mov eax, cr4
    or eax, (1 << 9) | (1 << 10)
    mov cr4, eax
%endmacro

test_main:
    SSE_ON
    xorps xmm0, xmm0
    xorps xmm1, xmm1
    mov esi, buf
    mov ecx, 64
.fill:
    mov byte [esi + ecx], 0x3F
    dec ecx
    jnz .fill
""" if not LONG else """
%macro SSE_ON 0
%endmacro
test_main:
    xorps xmm0, xmm0
    xorps xmm1, xmm1
    lea rsi, [rel buf]
    mov ecx, 64
.fill:
    mov byte [rsi + rcx], 0x3F
    dec ecx
    jnz .fill
""")
case_id = 1
def emit(expected, text):
    if LONG:
        text = text.replace("[esi]", "[rsi]")
    """run `text` (ESI is the address register) many times on aligned data, then once on a misaligned
    address inside the same hot loop, so the access that faults (or must not) is part of compiled code"""
    global case_id
    n = case_id
    case_id += 1
    if n in SKIP:
        return
    w("    ; %s" % text)
    w("    lea rsi, [rel buf]" if LONG else "    mov esi, buf")
    w("    mov ecx, 1200")
    if LONG:
        w("    lea rax, [rel .after%d]" % n)
        w("    mov [EXC_RESUME], rax")
    else:
        w("    mov dword [EXC_RESUME], .after%d" % n)
    w("    mov dword [EXC_VEC], -1")
    w(".hot%d:" % n)
    w("    cmp ecx, 1")
    w("    jne .keep%d" % n)
    w("    add rsi, 4" if LONG else "    add esi, 4")
    w(".keep%d:" % n)
    w("    %s" % text)
    w("    dec ecx")
    w("    jnz .hot%d" % n)
    w(".after%d:" % n)
    w("    mov qword [EXC_RESUME], 0" if LONG else "    mov dword [EXC_RESUME], 0")
    w("    cmp dword [EXC_VEC], %d" % expected)
    w("    je .ok%d" % n)
    w("    mov eax, [nfail]")
    w("    cmp eax, 16")
    w("    jae .full%d" % n)
    w("    mov byte [fails + eax], %d" % n)
    w(".full%d:" % n)
    w("    inc dword [nfail]")
    w(".ok%d:" % n)

ALL_CASES = []
for name, imm in LOADS:
    suffix = ", %s" % imm if imm else ""
    if name == "palignr" or name in ("shufps", "shufpd", "cmpps", "cmppd", "pshufd", "pshufhw", "pshuflw", "blendps", "blendpd", "pblendw", "dpps", "dppd", "roundps", "roundpd", "mpsadbw", "pcmpistri", "pcmpistrm"):
        pass
    emit(13, "%s xmm1, [esi]%s" % (name, suffix))
for name, kind in UNALIGNED_OK:
    if kind == "load":
        emit(-1, "%s xmm1, [esi]" % name)
    else:
        emit(-1, "%s [esi], xmm1" % name)
for text in SMALL_OK:
    emit(-1, text)
for name in STORES_ALIGNED:
    emit(13, "%s [esi], xmm1" % name)
w("""    cmp dword [nfail], 0
    je .pass
    ; report: id = number of wrong cases, actual / expected = the ids of the first 16 (one byte each)
    mov eax, [nfail]
    mov [RESULT_ID], eax
    mov eax, [fails]
    mov [RESULT_ACT], eax
    mov eax, [fails + 4]
    mov [RESULT_ACT + 4], eax
    mov eax, [fails + 8]
    mov [RESULT_EXP], eax
    mov eax, [fails + 12]
    mov [RESULT_EXP + 4], eax
    mov dword [RESULT], STATUS_FAIL
    hlt
.pass:
    PASS
nfail: dd 0
fails: times 16 db 0""")
w("align 16")
w("buf: times 160 db 0")
print("\n".join(out))

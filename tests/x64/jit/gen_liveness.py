#!/usr/bin/env python3
"""Generates 07_flag_liveness.asm: instruction sequences where the flags of one instruction are
consumed after other instructions (which may or may not touch them), checked against a model.
Run: ./gen_liveness.py > 07_flag_liveness.asm"""

V = [0, 1, 2, 0x7F, 0x80, 0xFF, 0x7FFFFFFF, 0x80000000, 0xFFFFFFFF, 0x7FFFFFFFFFFFFFFF,
     0x8000000000000000, 0xFFFFFFFFFFFFFFFF, 0x1234567890ABCDEF]
M = (1 << 64) - 1

def sub_flags(a, b, size=64):
    m = (1 << size) - 1
    a &= m; b &= m
    r = (a - b) & m
    return dict(cf=a < b, zf=r == 0, sf=bool(r >> (size - 1)), of=bool(((a ^ b) & (a ^ r)) >> (size - 1) & 1))

def add_flags(a, b, size=64):
    m = (1 << size) - 1
    a &= m; b &= m
    r = (a + b) & m
    return dict(cf=a + b > m, zf=r == 0, sf=bool(r >> (size - 1)), of=bool(((a ^ r) & (b ^ r)) >> (size - 1) & 1)), r

out = []
w = out.append
w("; EXPECT: pass")
w("; NATIVE: yes")
w('; V86: {"jit64_threshold": 10, "sync_jit": true}')
w("; DESC: jit64: flags consumed after other instructions, across jumps, and by adc / inc / shifts (generated by gen_liveness.py)")
w('%include "inc/long.inc"')
w("")
w("test_main:")
w("    xor r10d, r10d              ; number of mismatches")
tables = []
n = 0

def loop(title, body, rows):
    """rows: (a, b, expected) with rax = a, rbx = b before body; the body leaves a value in rdx"""
    global n
    n += 1
    w(f"    ; {title}")
    w(f"    lea rsi, [rel tbl{n}]")
    w(f"    mov ecx, {len(rows)}")
    w(f".l{n}:")
    w("    mov rax, [rsi]")
    w("    mov rbx, [rsi + 8]")
    w("    xor edx, edx")
    for line in body.split("\n"):
        w("    " + line.replace("@", str(n)))
    w("    mov rdi, [rsi + 16]")
    w("    cmp rdx, rdi")
    w("    setne dil")
    w("    movzx edi, dil")
    w("    add r10, rdi")
    w("    add rsi, 24")
    w("    dec ecx")
    w(f"    jnz .l{n}")
    w(f"    CHECK_EQ {n}, r10, 0")
    tables.append((n, [f"dq 0x{a:x}, 0x{b:x}, 0x{e:x}" for a, b, e in rows]))

pairs = [(a, b) for a in V for b in V]

# the carry flag of a cmp survives inc / dec / mov / lea in between
loop("cmp, then inc / dec / mov / lea, then jb",
     "cmp rax, rbx\ninc r12\ndec r8\nmov r9, rax\nlea r11, [rax + 1]\njb .t@\nxor edx, edx\njmp .e@\n.t@:\nmov edx, 1\n.e@:",
     [(a, b, int(sub_flags(a, b)["cf"])) for a, b in pairs])
# flags used after a jump (basic block boundary), by two different jumps
loop("cmp, jmp, then jl and je",
     "cmp rax, rbx\njmp .b@\n.b@:\nmov rdx, 0\njl .lt@\nje .eq@\njmp .e@\n.lt@:\nmov edx, 1\njmp .e@\n.eq@:\nmov edx, 2\n.e@:",
     [(a, b, 1 if ((a ^ (1 << 63)) < (b ^ (1 << 63))) else (2 if a == b else 0)) for a, b in pairs])
# dead flags: only the last operation counts
loop("add, sub, xor, inc, then cmp decides",
     "add rax, rbx\nsub rax, 5\nxor rax, rbx\ninc rax\nneg r12\ncmp rax, rbx\nsetb dl\nmovzx edx, dl",
     [(a, b, int(((((a + b) & M) - 5) & M ^ b) + 1 & M) < b) for a, b in pairs])
# adc uses the carry of the add, with unrelated instructions in between
loop("add, mov, lea, adc",
     "xor r12d, r12d\nadd rax, rbx\nmov r8, 7\nlea r9, [r8 + r8]\nadc r12, 0\nmov rdx, r12",
     [(a, b, int(add_flags(a, b)[0]["cf"])) for a, b in pairs])
# inc / dec keep the carry flag, but change the others
loop("add, inc, jc and jz after inc",
     "add rax, rbx\nsbb rdx, rdx\nneg rdx\ninc rax\nsetz r12b\nmovzx r12d, r12b\nlea rdx, [rdx + r12*2]",
     [(a, b, int(add_flags(a, b)[0]["cf"]) + 2 * int(((a + b + 1) & M) == 0)) for a, b in pairs])
# shifts by an immediate set the carry flag
loop("shl / shr / sar and the carry flag",
     "shl rax, 3\nsetc r12b\nshr rbx, 5\nsetc r13b\nmovzx edx, r12b\nmovzx r13d, r13b\nlea rdx, [rdx + r13*2]",
     [(a, b, ((a >> 61) & 1) + 2 * ((b >> 4) & 1)) for a, b in pairs])
loop("sar then sign and zero",
     "sar rax, 7\nsets r12b\nsetz r13b\nmovzx edx, r12b\nmovzx r13d, r13b\nlea rdx, [rdx + r13*2]",
     [(a, b, int(((a >> 63) & 1) == 1) + 2 * int((((a - (1 << 64)) if a >> 63 else a) >> 7) & M == 0)) for a, b in pairs])
# the flags survive a memory access and a call
loop("cmp, memory access, call, jae",
     "cmp rax, rbx\nmov rdi, [rel scratch]\nmov [rel scratch], rdi\nlea r8, [rel scratch]\njae .ae@\nxor edx, edx\njmp .e@\n.ae@:\nmov edx, 1\n.e@:",
     [(a, b, int(a >= b)) for a, b in pairs])
w("    PASS")
w("section .data")
w("align 16")
w("scratch: dq 0")
for k, rows in tables:
    w(f"align 16\ntbl{k}:")
    for r in rows:
        w("    " + r)
print("\n".join(out))

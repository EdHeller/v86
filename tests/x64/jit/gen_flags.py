#!/usr/bin/env python3
"""Generates 03_flags_conditions.asm: for many operand pairs and ALU operations, checks all 16
condition codes (via setcc) against a model of the x86 flags. Run: ./gen_flags.py > 03_flags_conditions.asm"""

VALUES = [0, 1, 2, 0x7F, 0x80, 0xFF, 0x7FFFFFFF, 0x80000000, 0xFFFFFFFF, 0x7FFFFFFFFFFFFFFF,
          0x8000000000000000, 0xFFFFFFFFFFFFFFFF, 0x1234567890ABCDEF, 0xFEDCBA0987654321]
CC = ["o", "no", "b", "ae", "e", "ne", "be", "a", "s", "ns", "p", "np", "l", "ge", "le", "g"]
OPS = ["cmp", "test", "add", "sub", "and", "or", "xor"]
REGS = {64: ("rax", "rbx"), 32: ("eax", "ebx"), 8: ("al", "bl")}

def model(op, size, a, b):
    m = (1 << size) - 1
    a &= m
    b &= m
    msb = size - 1
    if op == "add":
        r = a + b
        res = r & m
        cf = r > m
        of = ((a ^ res) & (b ^ res)) >> msb & 1
    elif op in ("sub", "cmp"):
        res = (a - b) & m
        cf = a < b
        of = ((a ^ b) & (a ^ res)) >> msb & 1
    else:
        res = {"and": a & b, "test": a & b, "or": a | b, "xor": a ^ b}[op]
        cf = False
        of = 0
    zf = res == 0
    sf = res >> msb & 1
    pf = bin(res & 0xFF).count("1") % 2 == 0
    of = bool(of)
    sf = bool(sf)
    return [of, not of, cf, not cf, zf, not zf, cf or zf, not (cf or zf), sf, not sf, pf, not pf,
            sf != of, sf == of, zf or sf != of, not zf and sf == of]

out = []
w = out.append
w("; EXPECT: pass")
w("; NATIVE: yes")
w('; V86: {"jit64_threshold": 10, "sync_jit": true}')
w("; DESC: jit64: all condition codes after cmp/test/add/sub/and/or/xor at 64, 32 and 8 bits (generated by gen_flags.py)")
w('%include "inc/long.inc"')
w("")
w("test_main:")
w("    xor r10d, r10d")
n = 0
tables = []
for size in (64, 32, 8):
    for op in OPS:
        n += 1
        ra, rb = REGS[size]
        pairs = [(a, b) for a in VALUES for b in VALUES]
        w(f"    ; {op} at {size} bits")
        w(f"    lea rsi, [rel tbl{n}]")
        w(f"    mov ecx, {len(pairs)}")
        w(f".l{n}:")
        w("    mov rax, [rsi]")
        w("    mov rbx, [rsi + 8]")
        w(f"    {op} {ra}, {rb}")
        w("    lea rdi, [rel out]")
        for k, cc in enumerate(CC):
            w(f"    set{cc} [rdi + {k}]")
        w("    mov r8, [rdi]")
        w("    mov r9, [rdi + 8]")
        w("    xor r8, [rsi + 16]")
        w("    xor r9, [rsi + 24]")
        w("    or r10, r8")
        w("    or r10, r9")
        w("    add rsi, 32")
        w("    dec ecx")
        w(f"    jnz .l{n}")
        w(f"    CHECK_EQ {n}, r10, 0")
        rows = []
        for a, b in pairs:
            e = model(op, size, a, b)
            q0 = sum(int(e[i]) << (8 * i) for i in range(8))
            q1 = sum(int(e[8 + i]) << (8 * i) for i in range(8))
            rows.append(f"dq 0x{a:x}, 0x{b:x}, 0x{q0:x}, 0x{q1:x}")
        tables.append((n, rows))
w("    PASS")
w("section .data")
w("align 16")
w("out: times 2 dq 0")
for n, rows in tables:
    w(f"align 16\ntbl{n}:")
    for r in rows:
        w("    " + r)
print("\n".join(out))
